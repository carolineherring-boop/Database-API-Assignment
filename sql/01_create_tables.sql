-- Run once in the SQL Editor of a NEW dedicated classroom project.
-- No DROP statements: existing data is not erased. If tables already exist, stop.
begin;
create table public.customers (
 customer_id bigint generated by default as identity (start with 1000) primary key,
 name text not null,
 email text not null unique,
 city text not null
);
create table public.products (
 product_id bigint generated by default as identity (start with 1000) primary key,
 product_name text not null,
 category text not null,
 price numeric(10,2) not null check (price >= 0)
);
create table public.orders (
 order_id bigint generated by default as identity (start with 1000) primary key,
 customer_id bigint not null references public.customers(customer_id),
 product_id bigint not null references public.products(product_id),
 quantity integer not null check (quantity > 0),
 order_date date not null default current_date,
 unit_price numeric(10,2) not null check (unit_price >= 0)
);
create index on public.orders(customer_id);
create index on public.orders(product_id);
alter table public.customers enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
-- No public access policies. Local admin scripts use the owner's secret key.
revoke all on public.customers, public.products, public.orders from anon, authenticated;
grant usage on schema public to service_role;
grant all on public.customers, public.products, public.orders to service_role;
grant usage, select on sequence public.customers_customer_id_seq,
 public.products_product_id_seq, public.orders_order_id_seq to service_role;
commit;
